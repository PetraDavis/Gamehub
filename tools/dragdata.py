def pack(ops):
    out = []
    for o in ops:
        k, c = o[0], o[1]
        a = list(o[2:])
        if k == 'r':
            a = [a[0] + OX, a[1] + OY, a[2], a[3], 0, 0]
            kk = 0
        elif k == 'c':
            a = [a[0] + OX, a[1] + OY, a[2], 0, 0, 0]
            kk = 1
        else:
            a = [a[0] + OX, a[1] + OY, a[2] + OX, a[3] + OY, a[4] + OX, a[5] + OY]
            kk = 2
        for v in a:
            assert 0 <= v < 256, o
        out += [kk, c] + a
    return bytes(out)


def lit(b):
    return repr(b)


